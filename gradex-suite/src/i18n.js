export const TRADUCTIONS = {};
for (const lg of LANGUES) {
  TRADUCTIONS[lg] = { ...BV[lg], ...GX[lg], methodes: BV[lg].methodes };
}

export function langueActuelle() {
  return localStorage.getItem('gradex_langue') || 'fr';
}
export function definirLangue(code) {
  localStorage.setItem('gradex_langue', code);
}
export function aChoisiUneLangue() {
  return localStorage.getItem('gradex_langue') !== null;
}
export function t(cle) {
  const dico = TRADUCTIONS[langueActuelle()] || TRADUCTIONS.fr;
  return dico[cle] ?? TRADUCTIONS.fr[cle] ?? cle;
}
export function metaMethode(id) {
  const dico = TRADUCTIONS[langueActuelle()] || TRADUCTIONS.fr;
  return (dico.methodes && dico.methodes[id]) || (TRADUCTIONS.fr.methodes && TRADUCTIONS.fr.methodes[id]) || {};
}
